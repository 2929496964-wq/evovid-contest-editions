"""Create five openly licensed, explicitly synthetic controlled video fixtures."""
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import cv2, numpy as np, json, subprocess
from vision.core import ffmpeg, digest
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'examples'; OUT.mkdir(exist_ok=True)
W,H,FPS=640,360,24

def frame(t,kind):
    y,x=np.indices((H,W)); a=np.zeros((H,W,3),np.uint8)
    a[:,:,0]=(x//20%2*95+40).astype('uint8'); a[:,:,1]=(y//20%2*80+55).astype('uint8');a[:,:,2]=125
    cv2.circle(a,(int(65+(t*70)%(W-130)),155),50,(100,210,230),-1)
    cv2.putText(a,'VISION DIRECTOR',(40,75),cv2.FONT_HERSHEY_SIMPLEX,.9,(240,245,255),2)
    cv2.line(a,(30,210),(610,210),(240,180,80),3)
    phase=int(t//2)
    if kind=='quality-lab':
        if phase==1:a=(a.astype(float)*.13).astype('uint8')
        elif phase==2:a=cv2.GaussianBlur(a,(41,41),12)
        elif phase==3:a[:]=0
        elif phase==4:a=cv2.bitwise_not(a)
    elif kind=='intentional-lowlight':a=(a.astype(float)*.1).astype('uint8')
    elif kind=='soft-background':a=cv2.GaussianBlur(a,(51,51),18)
    elif kind=='all-black':a[:]=0
    elif kind=='scene-cuts' and phase%2:a=cv2.bitwise_not(a)
    # Label is embedded below the analyzed main content, including black tests.
    if kind!='all-black' and not (kind=='quality-lab' and phase==3):
        cv2.rectangle(a,(0,300),(640,360),(22,23,32),-1)
        cv2.putText(a,'SYNTHETIC TEST | '+kind,(18,326),cv2.FONT_HERSHEY_SIMPLEX,.46,(188,185,200),1)
        cv2.putText(a,f'{t:05.2f}s  /  NOT REAL-WORLD BENCHMARK',(18,347),cv2.FONT_HERSHEY_SIMPLEX,.4,(160,154,180),1)
    return a

def make(kind,seconds):
    raw=OUT/(kind+'.avi'); target=OUT/('synthetic-'+kind+'.mp4')
    writer=cv2.VideoWriter(str(raw),cv2.VideoWriter_fourcc(*'MJPG'),FPS,(W,H))
    if not writer.isOpened():raise RuntimeError('Fixture VideoWriter failed')
    for i in range(round(seconds*FPS)):writer.write(frame(i/FPS,kind))
    writer.release()
    command=[ffmpeg(),'-hide_banner','-loglevel','error','-y','-i',str(raw),'-f','lavfi','-i','sine=frequency=440:sample_rate=48000',
             '-t',str(seconds),'-c:v','libx264','-threads','2','-pix_fmt','yuv420p','-c:a','aac','-b:a','96k','-movflags','+faststart',str(target)]
    subprocess.run(command,check=True);raw.unlink()
    return {'file':target.name,'sha256':digest(target),'duration':seconds,'fps':FPS,'width':W,'height':H,'origin':'Procedurally generated by tools/make_examples.py','license':'MIT (authored graphics); no third-party footage','synthetic':True,'notes':{'all-black':'Unlabeled pixels are deliberately all black; filename and manifest explicitly identify synthetic fixture.','intentional-lowlight':'Failure case: deliberate dark creative treatment receives warnings.','soft-background':'Failure case: deliberate optical softness receives warnings.'}.get(kind,'Controlled test, not real-world accuracy evidence.')}

if __name__=='__main__':
    manifest=[make('quality-lab',12),make('intentional-lowlight',6),make('soft-background',6),make('all-black',3),make('scene-cuts',8)]
    (OUT/'manifest.json').write_text(json.dumps(manifest,indent=2));print(json.dumps(manifest,indent=2))
